def basic_clean(df):
    # Remove completely empty unnamed columns
    unnamed_cols = [col for col in df.columns if str(col).startswith("Unnamed")]
    if unnamed_cols:
        df.drop(columns=unnamed_cols, inplace=True)
        print(f"Removed unnamed columns: {unnamed_cols}")

    # Convert flight date to datetime
    df["FL_DATE"] = pd.to_datetime(df["FL_DATE"], errors="coerce")
    print(f"FL_DATE dtype: {df['FL_DATE'].dtype}")

    # Standardize merged/retired carrier codes BEFORE any table is built
    # from OP_CARRIER, so dim_carrier and fact_flight always agree.
    df["OP_CARRIER"] = df["OP_CARRIER"].replace(AIRLINE_CODE_MAP)

    print(df.columns.tolist())
    return df

def load_and_append(input_dir, years):
    """
    Loads one CSV per year from `input_dir`, standardizes carrier codes
    via AIRLINE_CODE_MAP, tags each row with SOURCE_YEAR, and concatenates
    everything into a single DataFrame.
    """
    frames = []

    for year in years:
        # Adjust the pattern if your files are named differently
        # (e.g. "flights_2014.csv", "2014.csv", "On_Time_2014.csv"...)
        pattern = os.path.join(input_dir, f"*{year}*.csv")
        matches = glob.glob(pattern)

        if not matches:
            print(f"⚠️  No file found for {year} matching pattern: {pattern}")
            continue

        file_path = matches[0]
        print(f"Loading {year}: {file_path}")

        chunk = pd.read_csv(file_path, low_memory=False)

        # Standardize carrier codes right after loading (mergers)
        if "OP_CARRIER" in chunk.columns:
            chunk["OP_CARRIER"] = chunk["OP_CARRIER"].replace(AIRLINE_CODE_MAP)

        # Ensure SOURCE_YEAR exists even if the raw file doesn't have it
        chunk["SOURCE_YEAR"] = year

        # Parse date column if present
        if "FL_DATE" in chunk.columns:
            chunk["FL_DATE"] = pd.to_datetime(chunk["FL_DATE"], errors="coerce")

        frames.append(chunk)

    if not frames:
        raise FileNotFoundError(
            f"No files matched any of the years {years} in {input_dir}"
        )

    df_all = pd.concat(frames, ignore_index=True)
    print(f"\n✅ Loaded {len(df_all):,} rows across {len(frames)} year(s)")
    return df_all

