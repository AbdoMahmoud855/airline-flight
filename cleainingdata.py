def map_dimension_keys(fact_flight, mapping):
    for source_col, (dim, dim_col, key_col, fact_key_col) in mapping.items():

        if dim[dim_col].duplicated().any():
            raise ValueError(f"Duplicate values in {dim_col}")

        lookup = dim.set_index(dim_col)[key_col]
        fact_flight[fact_key_col] = fact_flight[source_col].map(lookup).astype("Int64")

        missing = fact_flight[fact_key_col].isna().sum()
        if missing:
            print(f"⚠️ {source_col}: {missing:,} unmapped rows")

    return fact_flight.drop(columns=list(mapping.keys()))

fact_flight = map_dimension_keys(fact_flight, FACT_DIM_MAPPING)

