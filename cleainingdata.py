def save_table_chunked(table, table_name, output_dir, chunk_size=500_000):
    file_path = os.path.join(output_dir, f"{table_name}.csv")
    total_rows = len(table)
    print(f"\n{table_name}: {total_rows:,} rows")

    with open(file_path, "w", encoding="utf-8", newline="") as f:

        for start in tqdm(range(0, max(total_rows, 1), chunk_size),
                          desc=f"Saving {table_name}", unit="chunk"):
            end = min(start + chunk_size, total_rows)
            table.iloc[start:end].to_csv(f, index=False, header=(start == 0))

    size_mb = os.path.getsize(file_path) / (1024**2)
    print(f"✅ Saved: {file_path} ({size_mb:,.1f} MB)")
    return file_path


