def create_dim_date(df):

    dates = (
        df["FL_DATE"]
        .dropna()
        .drop_duplicates()
        .sort_values()
        .reset_index(drop=True)
    )

    dim_date = pd.DataFrame({
        "Date": dates
    })

    # Date Key
    dim_date["DateKey"] = (
        dim_date["Date"]
        .dt.strftime("%Y%m%d")
        .astype(int)
    )

    # Date Attributes
    dim_date["Year"] = dim_date["Date"].dt.year

    dim_date["Quarter"] = (
        "Q" +
        dim_date["Date"]
        .dt.quarter
        .astype(str)
    )

    dim_date["Month"] = dim_date["Date"].dt.month

    dim_date["MonthName"] = (
        dim_date["Date"]
        .dt.month_name()
    )


    # Final column order
    dim_date = dim_date[
        [
            "DateKey",
            "Date",
            "Year",
            "Quarter",
            "Month",
            "MonthName",

        ]
    ]

    return dim_date

