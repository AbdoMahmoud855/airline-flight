def create_fact_delay(df, dim_delay_reason):

    fact_parts = []

    for _, reason in dim_delay_reason.iterrows():

        column = reason["DelayReasonCode"]
        reason_key = reason["DelayReasonKey"]

        if column not in df.columns:
            continue

        mask = (
            df[column].notna()
            & (df[column] > 0)
        )

        part = pd.DataFrame({
            "FlightKey": df.index[mask] + 1,
            "DelayReasonKey": reason_key,
            "DelayMinutes": df.loc[
                mask,
                column
            ]
        })

        fact_parts.append(part)

    fact_delay = pd.concat(
        fact_parts,
        ignore_index=True
    )

    return fact_delay

