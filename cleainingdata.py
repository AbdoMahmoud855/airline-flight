def create_dim_airport(df):

    airports = airportsdata.load("IATA")

    # Get all airport codes from Origin and Destination
    airport_codes = pd.concat([
        df["ORIGIN"],
        df["DEST"]
    ]).dropna().unique()

    airport_codes = sorted(
        str(code).strip().upper()
        for code in airport_codes
    )

    airport_rows = []

    for code in airport_codes:

        airport = airports.get(code)

        if airport:

            airport_rows.append({
                "AirportCode": code,
                "AirportName": airport.get("name"),
                "City": airport.get("city"),
                "Country": airport.get("country")
            })

        else:

            airport_rows.append({
                "AirportCode": code,
                "AirportName": "Unknown",
                "City": "Unknown",
                "Country": "Unknown"
            })

    dim_airport = pd.DataFrame(
        airport_rows
    )

    # Surrogate Key
    dim_airport.insert(
        0,
        "AirportKey",
        range(1, len(dim_airport) + 1)
    )

    return dim_airport

